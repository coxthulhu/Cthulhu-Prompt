/** Real Electron integration covers note files and the production renderer mutation bridge. */
const { test, describe, expect } = createPlaywrightTestSuite()
/** Shared workspace path; each test receives a fresh filesystem and Electron process. */
const WORKSPACE = '/ws/notes'
/** Stable fixture workspace identity generated by the repository's workspace factory. */
const WORKSPACE_ID = createDeterministicId(WORKSPACE)
/** Old timestamp makes owner lifecycle timestamp changes observable without sleeps. */
const ORIGINAL_TIME = '2020-01-01T00:00:00.000Z'

/** Starts both library kinds with categorized owners and a note-only filename collision. */
const startNotes = async (testSetup: TestSetup, kind: 'prompt' | 'template') => {
  /** Task library fixture retains ordered neighbors around the owner. */
  const prompts = createWorkspaceWithCollections(WORKSPACE, [
    { folderName: 'Source', displayName: 'Source', promptCollectionId: 'prompt-source', prompts: [
      { id: 'prompt-owner', title: 'Owner', promptText: 'Owner text', category: 'prompt-category' },
      { id: 'prompt-neighbor', title: 'Neighbor', promptText: 'Neighbor text', category: 'prompt-category' }
    ] },
    { folderName: 'Target', displayName: 'Target', promptCollectionId: 'prompt-target' }
  ])
  /** Template library supplies equivalent ordering without task statuses. */
  const templates = createWorkspaceWithTemplateCollections(WORKSPACE, [
    { folderName: 'Source', displayName: 'Source', collectionId: 'template-source', categories: [
      { categoryName: 'Category', displayName: 'Category', categoryId: 'template-category', templates: [
        { id: 'template-owner', title: 'Owner', templateText: 'Owner text' },
        { id: 'template-neighbor', title: 'Neighbor', templateText: 'Neighbor text' }
      ] }
    ] },
    { folderName: 'Target', displayName: 'Target', collectionId: 'template-target' }
  ])
  /** Selected library directory and original owner path. */
  const library = kind === 'prompt' ? 'Prompts' : 'Templates'
  /** Physical status folder shared by owners and notes. */
  const active = `${WORKSPACE}/${library}/Source/Active`
  await testSetup.setupFilesystem({
    ...prompts, ...templates,
    [`${WORKSPACE}/Prompts/Source/Categories/Category.category.json`]: JSON.stringify({
      id: 'prompt-category', displayName: 'Category', shortDescription: null, description: null
    }),
    [`${WORKSPACE}/Prompts/CollectionOrder.json`]: prompts[`${WORKSPACE}/Prompts/CollectionOrder.json`],
    [`${active}/Owner.note.md`]: `---\nid: blocker\ncreatedAt: "2020-01-01T00:00:00Z"\ntitle: Blocker\nstatus: ${kind === 'prompt' ? 'Todo' : 'Active'}\n---\nUnrelated note`
  }, { fileModifiedTimes: { [`${active}/Owner.${kind === 'prompt' ? 'prompt' : 'template'}.md`]: ORIGINAL_TIME } })
  await testSetup.setupFileDialog([getWorkspaceInfoPath(WORKSPACE)])
  /** Application startup exercises disk discovery before any note mutation. */
  const started = await testSetup.setupAndStart({ workspace: { scenario: 'none' } })
  await started.testHelpers.setupWorkspaceViaUI()
  await started.mainWindow.evaluate(async ({ workspaceId, kind }) => {
    await window.playwrightTestControls!.notes.loadCollection(workspaceId, `${kind}-source`)
    await window.playwrightTestControls!.notes.loadCollection(workspaceId, `${kind}-target`)
  }, { workspaceId: WORKSPACE_ID, kind })
  return { ...started, active, library }
}

/** Reads the persisted note through the renderer's authoritative collection. */
const readNote = (page: Page, id: string) => page.evaluate((id) => window.playwrightTestControls!.notes.getNote(id), id)

/** Changes visibility through the production renderer action. */
const setVisible = (page: Page, noteId: string, visible: boolean) => page.evaluate(
  ({ workspaceId, noteId, visible }) => window.playwrightTestControls!.notes.setAttachedNoteVisible(workspaceId, noteId, visible),
  { workspaceId: WORKSPACE_ID, noteId, visible }
)

/** Reads the production visibility default as well as saved values. */
const readVisible = (page: Page, noteId: string) => page.evaluate(
  ({ workspaceId, noteId }) => window.playwrightTestControls!.notes.getAttachedNoteVisible(workspaceId, noteId),
  { workspaceId: WORKSPACE_ID, noteId }
)

/** Verifies lifecycle cleanup in both SQLite and the reconciled renderer collection. */
const expectVisibilityRemoved = async (page: Page, app: ElectronApplication, noteId: string) => {
  expect(await readWorkspaceState(app, WORKSPACE_ID, 'attached-note', noteId)).toBeNull()
  expect(await page.evaluate(({ workspaceId, noteId }) =>
    window.playwrightTestControls!.notes.getAttachedNoteUiState(workspaceId, noteId),
  { workspaceId: WORKSPACE_ID, noteId })).toBeUndefined()
}

/** Reads physical modification times, optionally seeding an old time without rewriting content. */
const fileTime = (app: ElectronApplication, filePath: string, setTo?: string): Promise<string> => app.evaluate(({ app }, payload) => {
  app.emit('test-file-modified-time', payload)
  return (global as any).testFileModifiedTime
}, { filePath, setTo })

/** Sends malformed/stale requests through real IPC instead of bypassing main validation. */
const invoke = (page: Page, channel: string, command: object, expectations: object[] = []) => page.evaluate(
  ({ channel, command, expectations }) => window.electron.ipcRenderer.invoke(channel, {
    requestId: crypto.randomUUID(), clientId: window.ipcClientId, payload: { command, expectations }
  }), { channel, command, expectations }
)

